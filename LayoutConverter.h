#pragma once

#include <QString>
#include <QStringList>
#include <QHash>

/**
 * LayoutConverter — смена раскладки текста, набранного «не в той» раскладке.
 *
 * Идея: «сменить раскладку» = перекодировать каждый символ так, как если бы
 * ту же ФИЗИЧЕСКУЮ клавишу нажали в другой раскладке. Например, набранное в
 * английской раскладке «Ghbdtn» превращается в «Привет», если нажать те же
 * клавиши в русской раскладке. Учитываются оба регистра (уровни клавиши:
 * обычный и Shift), поэтому пунктуация верхнего регистра тоже конвертируется.
 * Работает и когда раскладок больше двух — можно циклически перебирать любую
 * из установленных в системе.
 *
 * Откуда берутся раскладки:
 *   • Linux — список из конфига рабочего стола (gsettings/GNOME, kxkbrc/KDE,
 *     setxkbmap/X11), а карта «клавиша+уровень → символ» каждой раскладки
 *     строится через libxkbcommon (та же библиотека, что и у самого Qt). Если
 *     libxkbcommon на этапе сборки не найдена — используется встроенная таблица
 *     us↔ru, чтобы функция не пропадала совсем.
 *   • macOS — список включённых источников ввода через TIS (Text Input Sources),
 *     карта клавиш — через UCKeyTranslate (Carbon). Работает с любыми
 *     установленными раскладками (Russian, Ukrainian, Greek, …).
 *
 * Вызовы — из UI-потока.
 */
class LayoutConverter
{
public:
    /** Ссылка на «физическую клавишу» и уровень (0 — base, 1 — Shift). */
    struct KeyRef {
        quint32 key = 0;
        int level = 0;
    };

    /** Одна раскладка: короткий код (us, ru, …) и карты перекодировки. */
    struct Layout {
        QString code;
        /** Составной ключ (клавиша<<3 | уровень) → символ. */
        QHash<quint64, QString> keyToChar;
        /** Символ → (клавиша, уровень). */
        QHash<QString, KeyRef> charToKey;
    };

    /**
     * Список установленных в системе раскладок в порядке рабочего стола.
     * Если определить не удалось — безопасный фолбэк {"us", "ru"}.
     * Результат кэшируется на время жизни процесса.
     */
    static QStringList availableLayouts();

    /** Есть ли вообще что конвертировать (хотя бы две раскладки с картами). */
    static bool available();

    /**
     * Перекодировать text из раскладки from в раскладку to.
     * Символы, которых нет в исходной раскладке (или для которых нет клавиши
     * в целевой), остаются как есть (пробелы, эмодзи и пр.).
     * Возвращает пустую строку, если ни один символ не удалось перекодировать
     * (например, раскладки недоступны) — вызывающая сторона по этому признаку
     * не трогает буфер обмена.
     */
    static QString convert(const QString &text, const QString &from,
                           const QString &to);

    /** Следующая раскладка после current (циклически по списку). */
    static QString nextLayout(const QString &current);

    /**
     * Предположить раскладку, в которой набран текст: побеждает та, в которой
     * на клавиши отображается больше всего букв. Пусто — если ни одна не
     * подходит (например, в тексте только цифры/заданные символы).
     * Нужно для ПЕРВОГО клика кнопки, когда запись ещё не «привязана» к
     * раскладке: так работают оба направления (us→ru и ru→us).
     */
    static QString guessLayout(const QString &text);

private:
    LayoutConverter() = delete;
};
